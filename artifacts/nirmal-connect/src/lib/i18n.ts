export type HierarchyKey = keyof typeof hierarchyAdminTranslations.en;

// `satisfies` above guarantees `ta` has the exact same key set as `en`,
// so the indexed access is structurally safe.
export function tHi<K extends HierarchyKey>(
  lang: Language,
  key: K,
): typeof hierarchyAdminTranslations.en[K] {
  const dict = hierarchyAdminTranslations[lang];
  return (dict[key] ?? hierarchyAdminTranslations.en[key]) as typeof hierarchyAdminTranslations.en[K];
}
